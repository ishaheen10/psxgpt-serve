#!/usr/bin/env node
// Generate apps/web/content/changelog.generated.ts from changes/*.json.
//
// changes/ is the SINGLE product-level change registry — the journal. No
// matter which repo the work happened in (pipeline, query engine, app), the
// event record lands here; the `system` field records where.
// The truth being changed stays with its code (PIPELINE_SPEC.md in
// psxgpt-pipeline, apps/analysis/spec.md here) — this registry is event
// metadata, not the contract.
//
// Same principle as sync-context.sh: exactly one editable copy; downstream
// copies are generated and never hand-edited. Run after adding a record:
//   node scripts/sync-changelog.mjs
//
// Record shape: { id, date (YYYY-MM-DD), system (pipeline|engine|app),
// seq (same-day ordering, higher = newer), tag (new|improvement|fix), title,
// points[], public, keystones? (consumed by psxgpt-pipeline's docs linter) }.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SERVE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REGISTRY = join(SERVE_ROOT, 'changes');
const OUTPUT = join(SERVE_ROOT, 'apps', 'web', 'content', 'changelog.generated.ts');
const SYSTEMS = new Set(['pipeline', 'engine', 'app']);

const entries = [];
const seenIds = new Set();
if (!existsSync(REGISTRY)) {
  throw new Error(`registry not found: ${REGISTRY}`);
}
for (const name of readdirSync(REGISTRY)) {
  if (!name.endsWith('.json')) continue;
  const record = JSON.parse(readFileSync(join(REGISTRY, name), 'utf8'));
  if (record.public === false) continue;
  for (const field of ['id', 'date', 'system', 'tag', 'title', 'points']) {
    if (record[field] === undefined) {
      throw new Error(`${join(REGISTRY, name)}: missing required field "${field}"`);
    }
  }
  if (!SYSTEMS.has(record.system)) {
    throw new Error(`${join(REGISTRY, name)}: system must be one of ${[...SYSTEMS].join('|')}`);
  }
  if (seenIds.has(record.id)) {
    throw new Error(`duplicate change id "${record.id}" (${join(REGISTRY, name)})`);
  }
  seenIds.add(record.id);
  entries.push(record);
}

entries.sort((a, b) =>
  b.date.localeCompare(a.date) || (b.seq ?? 0) - (a.seq ?? 0) || b.id.localeCompare(a.id),
);

const rows = entries.map(({ id, date, tag, title, points }) => ({ id, date, tag, title, points }));
const banner = `// GENERATED by scripts/sync-changelog.mjs — do not hand-edit.
// Ground truth: changes/*.json (the single product-level change registry).
// Add a record there, then run: node scripts/sync-changelog.mjs
`;
writeFileSync(
  OUTPUT,
  `${banner}
import type { ChangelogEntry } from './changelog';

export const GENERATED_CHANGELOG: ChangelogEntry[] = ${JSON.stringify(rows, null, 2)};
`,
);
console.log(`Wrote ${entries.length} entries -> ${OUTPUT}`);
